export function drawText(ctx, text, x, y, color, scale = 1, spacing = 1) {
  const s = String(text).toUpperCase();
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of s) {
    const g = G[ch] || G['?'];
    for (let r = 0; r < 8; r++) {
      const row = g[r];
      for (let c = 0; c < 8; c++) {
        if (row[c] === 'X') ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += 9 * scale;
  }
  return cx - x;
}

export function textWidth(text, scale = 1, spacing = 1) {
  return String(text).length * 9 * scale;
}
